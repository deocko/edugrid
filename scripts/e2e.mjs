// Ciclo demo de punta a punta:
// alta de alumno → grupo → asistencia → calificación → cargo → pago → estado de cuenta → CFDI demo (XML + PDF).
// Uso: con la app servida en QA_URL (por defecto vite preview), node scripts/e2e.mjs
import { createRequire } from 'node:module'
import { mkdirSync, readFileSync } from 'node:fs'
const require = createRequire(import.meta.url)
const { chromium } = require('playwright')
const BASE = process.env.QA_URL ?? 'http://localhost:4173/edugrid/'
const OUT = process.env.QA_OUT ?? 'qa-output'
mkdirSync(OUT, { recursive: true })

const step = (m) => console.log(`✓ ${m}`)
const browser = await chromium.launch()
const ctx = await browser.newContext({ viewport: { width: 390, height: 844 }, acceptDownloads: true })
const page = await ctx.newPage()
page.on('pageerror', (e) => { console.error('Error de página:', e.message); process.exitCode = 1 })

const go = async (path) => { await page.goto(`${BASE}#${path}`); await page.waitForLoadState('networkidle') }
const logout = async () => { await page.getByRole('button', { name: 'Salir de la cuenta demo' }).click(); await page.waitForURL(/#\/$/) }

await go('/')
await page.evaluate(() => localStorage.clear())
await go('/')
await page.getByRole('button', { name: 'Entrar como Administrador' }).click()
await page.waitForURL(/#\/admin$/)
step('Admin entró a su panel')

// 1. Alta de alumno en 4° de primaria A
await go('/admin/alumnos?alta=1')
const dlg = page.getByRole('dialog')
await dlg.getByLabel('Nombre(s)').first().fill('Ana')
await dlg.getByLabel('Apellidos').first().fill('Prueba Ejemplo')
await dlg.getByLabel('Fecha de nacimiento').fill('2016-05-04')
await dlg.getByLabel('Grupo').selectOption('gr-primaria-4A')
await dlg.getByLabel('Nombre(s)').nth(1).fill('Rosa')
await dlg.getByLabel('Apellidos').nth(1).fill('Ejemplo Demo')
await dlg.getByLabel('Teléfono').fill('55 0000 1111')
await dlg.getByRole('checkbox').check()
await dlg.getByRole('button', { name: 'Inscribir alumno' }).click()
await page.getByText('quedó inscrito en 4° de primaria A').waitFor()
const studentId = await page.evaluate(() => JSON.parse(localStorage.getItem('edugrid.demo.db.v1')).students.find((s) => s.firstName === 'Ana').id)
step(`Alumno inscrito (${studentId}) en 4° de primaria A`)
await logout()

// 2. Docente titular pasa lista y califica
await page.getByLabel('Cuenta demo').nth(1).selectOption('t14')
await page.getByRole('button', { name: 'Entrar como Docente' }).click()
await page.waitForURL(/#\/docente$/)
await go('/docente/asistencia?grupo=gr-primaria-4A')
await page.getByRole('radiogroup', { name: 'Asistencia de Ana Prueba Ejemplo' }).getByRole('radio', { name: 'Retardo' }).click()
await page.getByRole('button', { name: 'Guardar asistencia' }).click()
await page.getByText('Asistencia guardada').waitFor()
step('Docente guardó asistencia (Ana con retardo)')
await go('/docente/calificaciones')
await page.getByLabel('Grupo').selectOption('gr-primaria-4A')
await page.getByLabel('Ana Prueba Ejemplo').fill('9.5')
await page.getByRole('button', { name: 'Guardar', exact: true }).click()
await page.getByText('Calificaciones guardadas').waitFor()
step('Docente capturó calificación 9.5')
await go('/alumnos/al3')
if (!(await page.getByText('No tienes acceso').isVisible())) throw new Error('El docente pudo ver un alumno ajeno')
step('Docente no puede ver alumnos de otros grupos')
await logout()

// 3. Admin: cargo, pago, estado de cuenta y CFDI
await page.getByRole('button', { name: 'Entrar como Administrador' }).click()
await page.waitForURL(/#\/admin$/)
await go(`/pagos?registrar=cargo&alumno=${studentId}`)
await page.getByLabel('Vence el').fill('2026-12-15')
await page.getByRole('button', { name: 'Generar cargo' }).click()
await page.getByText('Cargo de').waitFor()
step('Cargo de inscripción generado')
await go(`/pagos?registrar=1&alumno=${studentId}`)
await page.getByLabel('Forma de pago').selectOption('efectivo')
await page.getByRole('button', { name: 'Registrar pago' }).click()
await page.getByText('registrado').first().waitFor()
step('Pago registrado en efectivo')
await go(`/pagos/estado/${studentId}`)
await page.getByText('Saldo pendiente').waitFor()
await page.getByRole('link', { name: 'Facturar este pago' }).click()
await page.getByRole('button', { name: 'Emitir factura demo' }).click()
await page.getByText('Facturas emitidas (1)').waitFor()
step('Estado de cuenta consultado y factura demo emitida')
const [xmlDl] = await Promise.all([page.waitForEvent('download'), page.getByRole('button', { name: /Descargar XML/ }).first().click()])
await xmlDl.saveAs(`${OUT}/factura-demo.xml`)
const xml = readFileSync(`${OUT}/factura-demo.xml`, 'utf8')
if (!xml.includes('Version="4.0"') || !xml.includes('DEMO') || !xml.includes('tfd:TimbreFiscalDigital')) throw new Error('XML CFDI incompleto')
const [pdfDl] = await Promise.all([page.waitForEvent('download'), page.getByRole('button', { name: /Descargar PDF/ }).first().click()])
await pdfDl.saveAs(`${OUT}/factura-demo.pdf`)
const pdf = readFileSync(`${OUT}/factura-demo.pdf`)
if (pdf.subarray(0, 4).toString() !== '%PDF' || !pdf.includes('DEMO')) throw new Error('PDF sin marca DEMO')
step(`CFDI demo descargado: XML (${xml.length} bytes) y PDF (${pdf.length} bytes) con marca DEMO`)
await go(`/pagos/estado/${studentId}`)
await page.getByText('Factura DEMO1').waitFor()
step('El estado de cuenta muestra la factura')
await go('/admin/bitacora')
await page.getByText('Emitió factura demo').waitFor()
step('La bitácora registró todo el ciclo')
await logout()

// 4. Papá: solo ve a sus hijos
await page.getByRole('button', { name: 'Entrar como Papá' }).click()
await page.waitForURL(/#\/familia$/)
const body = await page.textContent('main')
if (body.includes('Ana Prueba')) throw new Error('Un papá ve a una alumna que no es su hija')
await go(`/familia/hijo/${studentId}`)
if (!(await page.getByText('No tienes acceso').isVisible())) throw new Error('Un papá pudo abrir a otra alumna')
step('Papá no ve alumnos que no son sus hijos')

await browser.close()
console.log('Ciclo demo completo sin errores.')
